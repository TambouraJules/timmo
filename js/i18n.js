const TI_LANG_KEY = "ti_lang";

function tiGetLang() {
  return localStorage.getItem(TI_LANG_KEY) || "fr";
}

function tiSetLang(lang) {
  localStorage.setItem(TI_LANG_KEY, lang);
  tiApplyLang();
}

function t(key) {
  const lang = tiGetLang();
  return (TI_TRANSLATIONS[lang] && TI_TRANSLATIONS[lang][key]) || TI_TRANSLATIONS.fr[key] || key;
}

function tiApplyLang() {
  const lang = tiGetLang();
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.setAttribute("placeholder", t(key));
  });
  document.querySelectorAll(".ti-lang-toggle [data-lang]").forEach(btn => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });
  document.dispatchEvent(new CustomEvent("ti:langchange"));
}

document.addEventListener("DOMContentLoaded", tiApplyLang);
